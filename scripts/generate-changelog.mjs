/**
 * Generates mobile/src/lib/changelogData.ts from the repo-root CHANGELOG.md, so the app
 * ships its own release notes without parsing Markdown at runtime (Metro needs nothing
 * special — the module is committed, like functions/src/data/teamCatalogue.ts).
 *
 * Parses `## [X.Y.Z.W] - DATE` version headings and their `### Added|Changed|Fixed|Removed`
 * sections (any other heading maps to "Other"). Bullets are column-0 `- ` lines; indented
 * non-blank lines continue the current bullet, all joined and whitespace-collapsed to
 * single spaces. Column-0 prose outside bullets is ignored.
 *
 * `--check` regenerates the module in memory and exits non-zero when it differs from the
 * committed file, so CI catches a CHANGELOG.md edit that never reached the app.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const SOURCE = "CHANGELOG.md";
const TARGET = "mobile/src/lib/changelogData.ts";
const VERSION_HEADING = /^## \[(\d+\.\d+\.\d+\.\d+)\] - (\S+)\s*$/;
const SECTION_KINDS = ["Added", "Changed", "Fixed", "Removed"];
const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;
const check = process.argv.includes("--check");

function collapse(text) {
  return text.replace(/\s+/g, " ").trim();
}

/** One entry per `## [version] - date` heading, in file order (newest first). */
function parseChangelog(markdown) {
  const entries = [];
  let entry = null;
  let section = null;

  for (const rawLine of `${markdown}\n`.split("\n")) {
    const line = rawLine.trimEnd();

    const versionMatch = VERSION_HEADING.exec(line);
    if (versionMatch) {
      const [, version, date] = versionMatch;
      if (!DATE_PATTERN.test(date) || Number.isNaN(Date.parse(date))) {
        throw new Error(`Invalid date "${date}" on version ${version}.`);
      }
      entry = { version, date, sections: [] };
      entries.push(entry);
      section = null;
      continue;
    }
    if (!entry) continue;

    const headingMatch = /^### (.+)$/.exec(line);
    if (headingMatch) {
      const title = headingMatch[1].trim();
      section = { kind: SECTION_KINDS.includes(title) ? title : "Other", items: [] };
      entry.sections.push(section);
      continue;
    }
    if (!section) continue;

    const bulletMatch = /^- (.+)$/.exec(line);
    if (bulletMatch) {
      section.items.push(collapse(bulletMatch[1]));
      continue;
    }

    // Indented text belongs to the bullet above it (wrapped lines and further
    // paragraphs of the same item). Anything else — blank lines, column-0 prose,
    // stray headings — is not part of any item.
    const isOpenBullet = /^\s+\S/.test(rawLine) && section.items.length > 0;
    if (isOpenBullet) {
      const last = section.items.length - 1;
      section.items[last] = collapse(`${section.items[last]} ${line}`);
    }
  }

  if (entries.length === 0) {
    throw new Error(`No "## [X.Y.Z.W] - DATE" versions found in ${SOURCE}.`);
  }
  return entries.map((e) => ({
    ...e,
    sections: e.sections.filter((s) => s.items.length > 0),
  }));
}

async function renderModule(entries) {
  const body = [
    "// Generated by scripts/generate-changelog.mjs from ../../CHANGELOG.md — do not edit.",
    "// Regenerate: npm run version:sync",
    'import type { ChangelogEntry } from "./changelog";',
    "",
    `export const CHANGELOG: ChangelogEntry[] = ${JSON.stringify(entries, null, 2)};`,
    "",
  ].join("\n");
  const { resolveConfig, format } = await import("prettier");
  const config = await resolveConfig(resolve(TARGET));
  return format(body, { ...config, filepath: resolve(TARGET) });
}

let entries;
try {
  entries = parseChangelog(readFileSync(resolve(SOURCE), "utf8"));
} catch (error) {
  console.error(error.message);
  process.exit(1);
}

const rendered = await renderModule(entries);

if (check) {
  let current = null;
  try {
    current = readFileSync(resolve(TARGET), "utf8");
  } catch {
    console.error(`${TARGET} is missing. Run \`npm run changelog:generate\`.`);
    process.exit(1);
  }
  if (current !== rendered) {
    console.error(`${TARGET} is stale relative to ${SOURCE}. Run \`npm run changelog:generate\`.`);
    process.exit(1);
  }
  console.log(`${TARGET} is fresh (${entries.length} versions).`);
  process.exit(0);
}

writeFileSync(resolve(TARGET), rendered);
console.log(`Wrote ${TARGET} (${entries.length} versions, newest ${entries[0].version}).`);
